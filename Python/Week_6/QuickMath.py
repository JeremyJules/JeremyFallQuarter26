def Add(num1, num2):
    return num1 + num2
sum = Add(7, 18)
print(sum)

def Subtract(num1, num2):
   return num1 - num2
dif = Subtract(34, 12)
print(dif)

def Multiply(num1, num2):
   return num1 * num2
product = Multiply(7, 9)
print(product)

def Divide(num1, num2):
   return num1 / num2
quotient = Divide(48, 12)
print(quotient)